"""
ip:网络环境下每台计算机的唯一标识,通过ip地址可以找到指定的计算机
    ip地址由4个数字组成,每个数字的范围是0-255,数字之间用点分隔开来,例如:192.168.1.1
    ip给机器看的
域名:网络环境下每台计算机的唯一标识,通过域名可以找到指定的计算机
    域名由多个部分组成,每个部分之间用点分隔开来,例如:www.baidu.com
    域名给人看的
域名解析:将域名转换为ip地址的过程,通过域名解析可以找到指定的计算机
域名解析服务器:负责将域名转换为ip地址的服务器,例如:DNS服务器
端口:计算机上运行的程序的唯一标识,通过端口可以找到指定的程序
    端口号是一个16位的整数,范围是0-65535,其中0-1023是系统保留端口,1024-49151是注册端口,49152-65535是动态端口
    端口给程序看的
协议:计算机之间通信的规则,通过协议可以实现计算机之间的通信
    常见的协议有:HTTP,HTTPS,FTP,SMTP等
tcp:传输控制协议,是一种面向连接的协议,通过tcp可以实现可靠的通信(需要通信双方先确定通信后在发送数据，过程三次握手)
udp:用户数据报协议,是一种无连接的协议,通过udp可以实现不可靠但快速的通信(群发信息，不用管是否收到，过程不需要三次握手)
"""